// Deterministic string hash helper
function hashStr(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = ((h << 5) - h + s.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

function pickFromPool(poolName, key) {
  const pool = POOLS[poolName] || POOLS.building;
  return pool[hashStr(key) % pool.length];
}

